# Writes shim/CaBundle.hx (into the directory given) from a PEM file: Mozilla's
# CA certificates as curl publishes them (https://curl.se/docs/caextract.html),
# which lix trusts besides the system's, as node (and so the npm package) does.
#   python3 tools/lix/cabundle.py <cacert.pem> <sha256> <out dir>
import hashlib, json, os, sys
pem, sha, out = sys.argv[1:4]
data = open(pem, 'rb').read()
if hashlib.sha256(data).hexdigest() != sha:
    sys.exit('cabundle.py: %s does not have the expected sha256' % pem)
# the certificates only (the comments name their owners, not all in ASCII)
certs, cur = [], None
for line in data.decode('utf-8').splitlines():
    if line.startswith('-----BEGIN CERTIFICATE-----'):
        cur = []
    if cur is not None:
        cur.append(line)
        if line.startswith('-----END CERTIFICATE-----'):
            certs.append('\n'.join(cur))
            cur = None
os.makedirs(os.path.join(out, 'shim'), exist_ok=True)
target = os.path.join(out, 'shim', 'CaBundle.hx')
with open(target + '.tmp', 'w') as f:
    f.write('package shim;\n\n// generated by tools/lix/cabundle.py from %s (%d certificates)\n' % (os.path.basename(pem), len(certs)))
    f.write('class CaBundle {\n\tpublic static final PEM = %s;\n}\n' % json.dumps('\n'.join(certs) + '\n'))
os.replace(target + '.tmp', target)
