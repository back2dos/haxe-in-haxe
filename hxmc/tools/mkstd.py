#!/usr/bin/env python3
"""Builds bin/hxmc/std, the hxmc target's std, from hxmc/std (hxmc/README.md, "Std").

    python3 hxmc/tools/mkstd.py [out dir]

Programs are typed with `-cp bin/hxmc/std --custom-target hxmc` (given last:
the last class path wins). The macro context (Eval) shares class paths with
the program, so every override of an upstream module keeps the original
source for Eval:

    package ...;  #if eval <original> #else <hxmc implementation> #end

Modules of hxmc's own (the `hxmc` package: the runtime's externs) are copied
as they are. HAXE_STD_PATH names the upstream std (default haxe/std). Files
are rewritten only when their content changes.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "hxmc", "std")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "bin", "hxmc", "std")
STD = os.environ.get("HAXE_STD_PATH") or os.path.join(ROOT, "haxe", "std")


def split_package(text):
    m = re.search(r"^\s*package\s+[\w.]*\s*;", text, re.M)
    return (m.group(0).strip(), text[:m.start()] + text[m.end():]) if m else ("", text)


def write(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)


for dirpath, _, files in os.walk(SRC):
    for f in sorted(files):
        rel = os.path.relpath(os.path.join(dirpath, f), SRC)
        ours = open(os.path.join(SRC, rel)).read()
        orig = None
        for cand in (os.path.join(STD, "eval", "_std", rel), os.path.join(STD, rel)):
            if os.path.exists(cand):
                orig = open(cand).read()
                break
        dst = os.path.join(OUT, rel)
        if orig is None or not rel.endswith(".hx"):  # hxmc's own module (e.g. hxmc.Native)
            write(dst, ours)
            continue
        pkg, body = split_package(ours)
        _, obody = split_package(orig)
        write(dst, f"// GENERATED by hxmc/tools/mkstd.py from hxmc/std/{rel}\n{pkg}\n#if eval\n{obody}\n#else\n{body}\n#end\n")
open(os.path.join(OUT, ".stamp"), "w").close()
