#!/usr/bin/env python3
"""HXB conformance cases from the upstream display test snippets.

Extracts every snippet of haxe/tests/display/src/cases/*.hx the way
test/display.py does (markers removed, `@:funcCode` wrapped, `@:filename`
honoured), writes it to test/generated/display-snippets/<Case>-<method>/ and
writes a case list for test/conformance.py that compiles the snippet's module
normally (no display request) to HXB for Eval, with the display tests' class
path (`-cp src-misc`). Many snippets are deliberately incomplete; when the
reference rejects one, the case is an expected failure and the port must
reject it too.

Usage:
  python3 test/display-snippet-cases.py
  HAXE_REFERENCE=haxe/haxe python3 test/conformance.py --cases test/generated/display-snippets/cases.txt [--hxb-lib]
"""
import pathlib, shlex, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "test"))
import display  # noqa: E402

GENERATED = ROOT / "test/generated/display-snippets"


def main():
    lines = ["# Generated by test/display-snippet-cases.py; do not edit."]
    count = 0
    for path in sorted(display.CASES.glob("*.hx")):
        for t in display.parse_case_file(path):
            name = "display-%s-%s" % (t["case"], t["name"])
            d = GENERATED / ("%s-%s" % (t["case"], t["name"]))
            target = d / t["filename"]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(t["source"])
            module = t["filename"][:-3].replace("/", ".") if t["filename"].endswith(".hx") else t["filename"]
            args = ["-cp", ".", "-cp", str(display.SRC_MISC), "-D", "message.reporting=classic", module, "--interp"]
            lines.append(" ".join(shlex.quote(a) for a in ["hxml", name, str(d.relative_to(ROOT))] + args))
            count += 1
    (GENERATED / "cases.txt").write_text("\n".join(lines) + "\n")
    print("%d snippet cases written to %s" % (count, (GENERATED / "cases.txt").relative_to(ROOT)))


if __name__ == "__main__":
    main()
