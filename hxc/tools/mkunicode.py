#!/usr/bin/env python3
# Writes hxc/std/hxc/RegexUnicode.hx, the Unicode tables of the hxc regular
# expression engine (hxc/Regex.hx), from Python's unicodedata. They follow
# PCRE2 10.42 with PCRE2_UTF | PCRE2_UCP (what Eval and HashLink compile EReg
# with):
#   \d  \p{Nd}
#   \w  \p{L} | \p{N} | _
#   \s  \p{Z} | \h | \v
#   [:alpha:] \p{L}, [:alnum:] \p{L}|\p{N}, [:lower:] \p{Ll}, [:upper:] \p{Lu}
# and caseless matching through sets of characters that are case variants of
# each other (simple lower/upper/fold mappings, closed transitively), as
# PCRE2's caseless sets.
import os, sys, unicodedata

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for c in range(MAX):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out += [start, c - 1]
            start = None
    if start is not None:
        out += [start, MAX - 1]
    return out


def cat(c):
    return unicodedata.category(chr(c))


H = {0x09, 0x20, 0xA0, 0x1680, 0x180E, *range(0x2000, 0x200B), 0x202F, 0x205F, 0x3000}
V = {*range(0x0A, 0x0E), 0x85, 0x2028, 0x2029}

tables = {
    "DIGIT": ranges(lambda c: cat(c) == "Nd"),
    "WORD": ranges(lambda c: cat(c)[0] in "LN" or c == 0x5F),
    "SPACE": ranges(lambda c: cat(c)[0] == "Z" or c in H or c in V),
    "ALPHA": ranges(lambda c: cat(c)[0] == "L"),
    "ALNUM": ranges(lambda c: cat(c)[0] in "LN"),
    "LOWER": ranges(lambda c: cat(c) == "Ll"),
    "UPPER": ranges(lambda c: cat(c) == "Lu"),
}

# caseless sets: union-find over single-character case mappings
parent = {}


def find(c):
    while parent.get(c, c) != c:
        c = parent[c]
    return c


def union(a, b):
    a, b = find(a), find(b)
    if a != b:
        parent[max(a, b)] = min(a, b)


for c in range(MAX):
    # surrogates; the Turkish dotted and dotless i stay out of the i/I set
    if 0xD800 <= c <= 0xDFFF or c in (0x130, 0x131):
        continue
    s = chr(c)
    for m in (s.lower(), s.upper(), s.casefold()):
        if len(m) == 1 and ord(m) != c:
            union(c, ord(m))
members = {}
for c in list(parent):
    members.setdefault(find(c), []).append(c)
for r in list(members):
    members[r] = sorted(set(members[r]) | {r})
fold_src, fold_rep = [], []
for r, ms in members.items():
    if len(ms) > 1:
        for m in ms:
            fold_src.append(m)
            fold_rep.append(ms[0])
order = sorted(range(len(fold_src)), key=lambda i: fold_src[i])
fold_src = [fold_src[i] for i in order]
fold_rep = [fold_rep[i] for i in order]


def enc(xs):
    # deltas from the previous number, base 36, comma-separated
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out, prev = [], 0
    for x in xs:
        d, s = x - prev, ""
        prev = x
        neg = d < 0
        d = abs(d)
        while True:
            s = digits[d % 36] + s
            d //= 36
            if d == 0:
                break
        out.append(("-" if neg else "") + s)
    return ",".join(out)


out = [
    "package hxc;",
    "",
    "// GENERATED by hxc/tools/mkunicode.py (Unicode %s): the Unicode tables" % unicodedata.unidata_version,
    "// of hxc.Regex (PCRE2_UCP classes and caseless sets), decoded on first use.",
    "// Ranges are sorted inclusive (lo, hi) pairs; FOLD_SRC is sorted and",
    "// FOLD_REP[i] is the smallest member of FOLD_SRC[i]'s caseless set.",
    "// Encoding: each number's difference from the previous one, base 36, comma-separated.",
    "class RegexUnicode {",
]
for name, r in list(tables.items()) + [("FOLD_SRC", fold_src), ("FOLD_REP", fold_rep)]:
    out.append("\tpublic static var %s(get, null):Array<Int>;" % name)
    out.append("\tstatic function get_%s() return %s != null ? %s : %s = decode(\"%s\");" % (name, name, name, name, enc(r)))
out.append("""
	static function decode(s:String):Array<Int> {
		var out = [], prev = 0, i = 0, n = s.length;
		while (i < n) {
			var neg = StringTools.fastCodeAt(s, i) == "-".code;
			if (neg) i++;
			var v = 0;
			while (i < n) {
				var c = StringTools.fastCodeAt(s, i++);
				if (c == ",".code) break;
				v = v * 36 + (c <= "9".code ? c - "0".code : c - "a".code + 10);
			}
			prev += neg ? -v : v;
			out.push(prev);
		}
		return out;
	}""")
out.append("}")
open(os.path.join(root, "std", "hxc", "RegexUnicode.hx"), "w").write("\n".join(out) + "\n")
