#!/usr/bin/env python3
# Builds bin/hxc/std (the hxc target's std overrides) from hxc/std. The macro
# context (Eval) shares class paths with the program, so every override keeps
# the original std source for Eval:
#   package ...;  #if eval <original> #else <hxc implementation> #end
import os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src, out, std = os.path.join(root, "std"), os.path.join(root, "..", "bin", "hxc", "std"), os.path.join(root, "..", "haxe", "std")
def split_package(text):
    m = re.search(r"^\s*package\s+[\w.]*\s*;", text, re.M)
    return (m.group(0).strip(), text[:m.start()] + text[m.end():]) if m else ("", text)
for dirpath, _, files in os.walk(src):
    for f in files:
        rel = os.path.relpath(os.path.join(dirpath, f), src)
        ours = open(os.path.join(src, rel)).read()
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        orig = None
        for cand in (os.path.join(std, "eval", "_std", rel), os.path.join(std, rel)):
            if os.path.exists(cand):
                orig = open(cand).read()
                break
        if orig is None:  # hxc-only module (e.g. hxc.Native)
            open(dst, "w").write(ours)
            continue
        pkg, body = split_package(ours)
        _, obody = split_package(orig)
        open(dst, "w").write(f"// GENERATED by hxc/tools/mkstd.py from hxc/std/{rel}\n{pkg}\n#if eval\n{obody}\n#else\n{body}\n#end\n")
