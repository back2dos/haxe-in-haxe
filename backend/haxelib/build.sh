#!/bin/sh
# EXPERIMENTAL: assembles the hxc haxelib package in bin/haxelib/hxc and
# zips it to bin/haxelib/hxc.zip (`haxelib install bin/haxelib/hxc.zip`, or
# `haxelib dev hxc bin/haxelib/hxc` while testing).
#
#   sh backend/haxelib/build.sh
#
# Package layout:
#   bin/hxc.com   the compiler (port + C backend) as a Cosmopolitan APE binary
#                 that runs on Linux, macOS, Windows and the BSDs (x86-64 and
#                 arm64), with the Haxe std subset in its own zip (/zip/std)
#   hxstd/        the class path: the hxc target's std overrides (backend/std)
#                 and hxc/{Boot,Build,Run}.hx (the init macro and `haxelib run hxc`)
#   rt/           the C runtime, compiled with the generated C on the user's machine
#   extraParams.hxml   --macro hxc.Boot.init(), added by -lib hxc
#
# The user's Haxe types the program and writes HXB; bin/hxc.com reads it
# (--hxb-lib) and lowers it to C. The archive's format must match the
# compiler hxc.com was built from (haxe/, see hxc.json).
#
# Needs: node, haxe/haxe (backend/build.sh), cosmocc on PATH (bench/COSMO.md).
# SKIP_GEN=1 reuses the generated C, SKIP_COM=1 reuses the binary.
set -eu
cd "$(dirname "$0")/../.."
HAXE=${HAXE:-haxe/haxe}
B=bin/haxelib/build
P=bin/haxelib/hxc
mkdir -p "$B"

python3 backend/tools/mkstd.py
# 1. the backend tool (port + C backend) as C, generated by the JS build of itself
if [ -z "${SKIP_GEN:-}" ]; then
	"$HAXE" -cp src -cp backend/src -main backend.Main -lib hxnodejs -cp bench/js-shims --js bin/backend/wbk.js -w -WDeprecated
	HAXE_STD_PATH=$PWD/haxe/std node --stack-size=65500 bin/backend/wbk.js "$B/hxc" -cp backend/std \
		-cp src -cp backend/src -cp bench/js-shims -main backend.Main -D disable-parallelism \
		--custom-target hxc > "$B/wbk.log" 2>&1 || { cat "$B/wbk.log"; exit 1; }
fi

# 2. the APE binary. Macros run in the bundled Eval: no mbedtls/libuv in the
# portable build yet (their natives fail when called)
if [ -z "${SKIP_COM:-}" ] || [ ! -f "$B/hxc.com" ]; then
	cosmocc -O2 -w -fno-strict-aliasing -DHXC_NO_SSL -DHXC_NO_UV -I backend/rt "$B/hxc.c" backend/rt/rt*.c -lm -o "$B/hxc.com"
fi

# 3. the package
rm -rf "$P" && mkdir -p "$P/bin" "$P/rt"
cp "$B/hxc.com" "$P/bin/hxc.com"
rm -rf "$B/std" && mkdir -p "$B/std"
cp haxe/std/*.hx "$B/std/"
cp -r haxe/std/haxe haxe/std/sys haxe/std/eval "$B/std/"
(cd "$B" && zip -qr -9 "../../../$P/bin/hxc.com" std)
# not std/: haxe looks for its own std in ./std, and haxelib runs Run.hx from the library root
cp -r backend/std "$P/hxstd"
cp -r backend/haxelib/hxc/. "$P/hxstd/hxc/"
cp backend/rt/*.h backend/rt/rt*.c "$P/rt/"
cp backend/haxelib/haxelib.json backend/haxelib/README.md backend/haxelib/extraParams.hxml "$P/"
printf '{"haxe": "%s", "commit": "%s"}\n' "$("$HAXE" -version 2>&1)" "$(git -C haxe rev-parse --short HEAD)" > "$P/hxc.json"
cp haxe/LICENSE "$P/LICENSE.txt"
rm -f bin/haxelib/hxc.zip
(cd "$P" && zip -qr -9 ../hxc.zip .)
ls -l "$P/bin/hxc.com" bin/haxelib/hxc.zip
